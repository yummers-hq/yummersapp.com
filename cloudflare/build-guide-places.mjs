// Writes guide-places.js: each guide place's clean name, kind, price and when, and each guide's cover place.
// Usage: node cloudflare/build-guide-places.mjs <final-guides.json>... --answers <dir of {guideSlug}--{restaurantId}.json>
// Rerun after the team edits the fill-in page, then commit the output.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const args = process.argv.slice(2), at = args.indexOf("--answers");
const files = args.slice(0, at), dir = args[at + 1];
// What the guide's topic says, unless a name matches an exception (the database's cuisine_type is too loose: "International", "Asian").
const DEFAULT = { "korean-restaurants-phnom-penh": "Korean", "khmer-food-phnom-penh": "Khmer", "bbq-phnom-penh": "BBQ", "street-food-phnom-penh": "Street food", "rooftop-bars-phnom-penh": "Rooftop bar", "vegan-vegetarian-phnom-penh": "Vegetarian" };
const KIND = [[/buffet/i, "Korean BBQ buffet"], [/Silla|Jaru|Sikgaek/, "Korean"], [/Melo/, "Korean fusion"], [/Korean|Dae Jang|Bornga|Sookdal|Dosegi/, "Korean BBQ"], [/Gyu-Kaku|Uraetei|Yakiniku/, "Japanese BBQ"], [/Smoke American/, "American BBQ"],
    [/KohKong/, "Khmer noodles"], [/Meatball/, "Meatball soup"], [/Midnight/, "Noodles"], [/Night Market/, "Night market"], [/Sthāni/, "Vegan"], [/MDSK/, "Indian vegetarian"]];
const short = (w) => { // at most 3 words, cut at a clause
    let s = w.split(",")[0].replace(/\s(or an|at|by|on|from|before|after|with|for|to)\s.*/, "");
    if (s.split(" ").length > 3) s = s.split(" or ")[0];
    return s;
};

const places = {}, covers = {};
for (const f of files) for (const g of JSON.parse(readFileSync(f, "utf8"))) {
    covers[g.slug] = g.slug.startsWith("korean") ? g.places.at(-1).id : g.slug.startsWith("khmer") ? g.places[2].id : g.places[0].id;
    for (const p of g.places) {
        if (places[p.id]) continue; // a place in two guides keeps its first name
        let a = {};
        try { a = JSON.parse(readFileSync(`${dir}/${g.slug}--${p.id}.json`, "utf8")); } catch {} // no answer yet: no chips
        places[p.id] = { name: p.name, kind: KIND.find(([re]) => re.test(p.name))?.[1] || DEFAULT[g.slug],
            ...(a.price && { price: a.price }), ...(a.when && { when: short(a.when) }) };
    }
}
writeFileSync(new URL("guide-places.js", import.meta.url), `// Generated by build-guide-places.mjs; do not edit. Hand-kept until the answers live in the database: rerun the script after the team edits the fill-in page.
export const PLACES = ${JSON.stringify(places, null, 1)};
export const COVERS = ${JSON.stringify(covers, null, 1)};
`);
console.log(Object.keys(places).length, "places,", Object.keys(covers).length, "guides");
